-- 1. TABLA DE TRABAJOS
CREATE TABLE IF NOT EXISTS public.trabajos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descripcion TEXT DEFAULT '',
    imagen_url TEXT NOT NULL,
    orden INT DEFAULT 1,
    activo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABLA DE CONFIGURACIÓN Y CONTACTO
CREATE TABLE IF NOT EXISTS public.configuracion (
    id INT PRIMARY KEY DEFAULT 1,
    whatsapp_numero TEXT NOT NULL DEFAULT '5491166340462',
    email_contacto TEXT NOT NULL DEFAULT 'info@montajessur.com',
    telefono_contacto TEXT DEFAULT 'Atención comercial y urgencias técnicas',
    cobertura_texto TEXT DEFAULT 'Cobertura y servicio en toda la región',
    texto_banner TEXT DEFAULT 'Consultanos sin compromiso. Te asesoramos y buscamos la mejor solución para tu necesidad.',
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. HABILITAR SEGURIDAD RLS (Row Level Security)
ALTER TABLE public.trabajos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracion ENABLE ROW LEVEL SECURITY;

-- Políticas para 'trabajos': cualquiera puede leer, solo administradores autenticados modifican
CREATE POLICY "Lectura pública de trabajos" ON public.trabajos
    FOR SELECT USING (true);

CREATE POLICY "Administradores pueden insertar trabajos" ON public.trabajos
    FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Administradores pueden actualizar trabajos" ON public.trabajos
    FOR UPDATE TO authenticated USING (true);

CREATE POLICY "Administradores pueden eliminar trabajos" ON public.trabajos
    FOR DELETE TO authenticated USING (true);

-- Políticas para 'configuracion': cualquiera puede leer, solo administradores modifican
CREATE POLICY "Lectura pública de configuración" ON public.configuracion
    FOR SELECT USING (true);

CREATE POLICY "Administradores pueden actualizar configuración" ON public.configuracion
    FOR UPDATE TO authenticated USING (true);

CREATE POLICY "Administradores pueden insertar configuración" ON public.configuracion
    FOR INSERT TO authenticated WITH CHECK (true);

